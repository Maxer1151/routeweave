"""Безопасность удаления Routeweave (uninstall.sh) без root.

Проверяются инварианты аудита:
- --dry-run ничего не меняет, печатает "DRY:" и не выводит значения секретов;
- без --purge при неинтерактивном запуске /etc/routeweave остаётся, есть
  предупреждение о ротации и команда с --purge;
- чужой бэкап drop-in systemd-resolved восстанавливается, а не затирается;
- маркер /etc/routeweave/owned различает routeweave/preexisting;
- в скрипте нет ufw --force reset и печати значений PANEL_PASS.
"""

import re
import shlex
import subprocess
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[1]
UNINSTALL = REPO_ROOT / "uninstall.sh"
MARKER = "# Generated by Routeweave installer"
OWN_CONTENT = "[Resolve]\nDNSStubListener=no\n"
FOREIGN_CONTENT = "[Resolve]\nDNSStubListener=yes\n"

BASE_ENV = {
    "PATH": "/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin",
    "LANG": "C.UTF-8",
    "LC_ALL": "C.UTF-8",
    "HOME": "/tmp",
}
# Значения нарочно уникальные: их не должно быть ни в stdout, ни в stderr.
SECRETS = {
    "PANEL_PASS": "panel-pass-UNIQUE-7f13",
    "MIHOMO_SECRET": "mihomo-secret-UNIQUE-9c2a",
    "TG_SECRET": "tg-secret-UNIQUE-4d81",
}


def make_etc(tmp_path: Path) -> Path:
    etc = tmp_path / "etc"
    (etc / "lists").mkdir(parents=True)
    (etc / "backup").mkdir()
    (etc / ".env").write_text(
        "\n".join(f'{key}="{value}"' for key, value in SECRETS.items())
        + '\nLAN_IFACE="eth0"\nWG_SUBNET="10.66.66.0/24"\n'
        'PANEL_PORT="8080"\nTS_IFACE="tailscale0"\nTS_SUBNET="100.64.0.0/10"\n',
        encoding="utf-8",
    )
    (etc / "lists" / "dpi.txt").write_text("example.org\n", encoding="utf-8")
    (etc / "config.yaml").write_text("mixed-port: 7890\n", encoding="utf-8")
    (etc / "ip_forward.orig").write_text("0\n", encoding="utf-8")
    return etc


def run_uninstall(etc: Path, *args: str) -> subprocess.CompletedProcess:
    env = dict(BASE_ENV)
    env["ROUTEWEAVE_ETC"] = str(etc)
    env["ROUTEWEAVE_BACKUP_DIR"] = str(etc / "backup")
    return subprocess.run(
        ["bash", str(UNINSTALL), *args],
        check=False,
        text=True,
        capture_output=True,
        env=env,
        stdin=subprocess.DEVNULL,
        timeout=60,
    )


def combined(proc: subprocess.CompletedProcess) -> str:
    return proc.stdout + proc.stderr


def test_dry_run_purge_changes_nothing_and_keeps_secrets_out_of_output(tmp_path):
    etc = make_etc(tmp_path)
    before = {
        p.relative_to(etc): p.read_bytes() for p in etc.rglob("*") if p.is_file()
    }

    proc = run_uninstall(etc, "--dry-run", "--purge")

    assert proc.returncode == 0, combined(proc)
    assert "DRY:" in proc.stdout
    # План purge и восстановление ip_forward видны, но не выполняются.
    assert "DRY: rm -rf" in proc.stdout
    assert "net.ipv4.ip_forward=0" in proc.stdout

    after = {
        p.relative_to(etc): p.read_bytes() for p in etc.rglob("*") if p.is_file()
    }
    assert after == before, "dry-run изменил файлы"

    output = combined(proc)
    for value in SECRETS.values():
        assert value not in output, "значение секрета попало в вывод"


def test_dry_run_without_purge_warns_and_keeps_files(tmp_path):
    etc = make_etc(tmp_path)

    proc = run_uninstall(etc, "--dry-run")

    assert proc.returncode == 0, combined(proc)
    output = combined(proc)
    assert "оставлен" in output.lower()
    assert "--purge" in output
    assert (etc / ".env").exists()
    assert (etc / "config.yaml").exists()
    assert (etc / "lists" / "dpi.txt").exists()
    for value in SECRETS.values():
        assert value not in output, "значение секрета попало в вывод"


def compose_line(output: str) -> str:
    """Строка плана dry-run, описывающая compose-шаг (итоговая сводка не в счёт)."""
    lines = [
        line for line in output.splitlines() if "DRY:" in line and "docker compose" in line
    ]
    assert len(lines) == 1, output
    return lines[0]


def test_dry_run_compose_down_passes_server_ip_inline(tmp_path):
    """SERVER_IP из .env подставляется инлайном, остальные значения не печатаются."""
    etc = make_etc(tmp_path)
    env_file = etc / ".env"
    env_file.write_text(
        env_file.read_text(encoding="utf-8")
        + "SERVER_IP='192.0.2.10'\n"
        # Апостроф внутри значения: compose-парсер env-файла на таком падает,
        # поэтому --env-file использовать нельзя.
        + "SOCKS_URL='socks5://u:pa'\\''ss@198.51.100.7:1080'\n",
        encoding="utf-8",
    )

    proc = run_uninstall(etc, "--dry-run")

    assert proc.returncode == 0, combined(proc)
    line = compose_line(proc.stdout)
    assert "SERVER_IP=192.0.2.10" in line, line
    assert "--env-file" not in line, line
    output = combined(proc)
    for value in SECRETS.values():
        assert value not in output, "значение секрета попало в вывод"
    # Прочие значения из .env не печатаются: для down нужен только SERVER_IP.
    assert "198.51.100.7" not in output, ".env попал в вывод"
    assert "socks5://" not in output, ".env попал в вывод"


def test_dry_run_compose_down_falls_back_without_env(tmp_path):
    """Без .env dry-run не падает: подставляется безопасный SERVER_IP."""
    etc = make_etc(tmp_path)
    (etc / ".env").unlink()

    proc = run_uninstall(etc, "--dry-run")

    assert proc.returncode == 0, combined(proc)
    line = compose_line(proc.stdout)
    assert "SERVER_IP=127.0.0.1" in line, line
    assert "--env-file" not in line, line


def extract_function(name: str, script: Path = UNINSTALL) -> str:
    text = script.read_text(encoding="utf-8")
    match = re.search(
        rf"^{re.escape(name)}\(\) \{{\n.*?^\}}\n", text, re.MULTILINE | re.DOTALL
    )
    assert match, f"{script.name}: не найдена функция {name}"
    return match.group(0)


def extract_marker(script: Path = UNINSTALL) -> str:
    text = script.read_text(encoding="utf-8")
    match = re.search(r"^RESOLVED_MARKER=.*$", text, re.MULTILINE)
    assert match, f"{script.name}: не найдена константа RESOLVED_MARKER"
    return match.group(0) + "\n"


def dropin_script() -> str:
    return (
        extract_marker()
        + extract_function("is_routeweave_dropin")
        + extract_function("plan_dropin_action")
        + extract_function("restore_dropin")
    )


@pytest.mark.parametrize(
    ("cur_kind", "bak_kind", "expected"),
    [
        # install.sh перезаписал чужой drop-in: при удалении его надо вернуть.
        ("own", "foreign", "restore"),
        # Бэкап — наша же конфигурация: восстанавливать нечего.
        ("own", "own", "remove"),
        ("own", "absent", "remove"),
        # Текущий файл чужой — не трогаем.
        ("foreign", "foreign", "keep"),
        ("foreign", "absent", "keep"),
        # Наш drop-in уже удалён, но чужой бэкап остался.
        ("absent", "foreign", "restore"),
    ],
)
def test_plan_dropin_action(cur_kind, bak_kind, expected, tmp_path):
    cur = tmp_path / "routeweave.conf"
    bak = tmp_path / "resolved-routeweave.conf.orig"
    contents = {"own": MARKER + "\n" + OWN_CONTENT, "foreign": FOREIGN_CONTENT}
    if cur_kind in contents:
        cur.write_text(contents[cur_kind], encoding="utf-8")
    if bak_kind in contents:
        bak.write_text(contents[bak_kind], encoding="utf-8")

    script = (
        "DRY_RUN=1\n"
        + dropin_script()
        + f'\nplan_dropin_action {shlex.quote(str(cur))} {shlex.quote(str(bak))}\n'
    )
    proc = subprocess.run(
        ["bash", "-c", script],
        check=False,
        text=True,
        capture_output=True,
        env=BASE_ENV,
    )
    assert proc.returncode == 0, proc.stderr
    assert proc.stdout.strip() == expected, proc.stdout


def test_restore_dropin_restores_foreign_backup(tmp_path):
    cur = tmp_path / "routeweave.conf"
    bak = tmp_path / "resolved-routeweave.conf.orig"
    cur.write_text(MARKER + "\n" + OWN_CONTENT, encoding="utf-8")
    bak.write_text(FOREIGN_CONTENT, encoding="utf-8")

    script = (
        "DRY_RUN=1\n"
        + "do_cp_a() { printf 'CP: %s -> %s\\n' \"$1\" \"$2\"; }\n"
        + "do_rm() { printf 'RM: %s\\n' \"$1\"; }\n"
        + "ok() { printf 'OK: %s\\n' \"$*\"; }\n"
        + "info() { :; }\n"
        + "warn() { :; }\n"
        + dropin_script()
        + f'\nrestore_dropin {shlex.quote(str(cur))} {shlex.quote(str(bak))}\n'
    )
    proc = subprocess.run(
        ["bash", "-c", script],
        check=False,
        text=True,
        capture_output=True,
        env=BASE_ENV,
    )

    assert proc.returncode == 0, proc.stderr
    # Чужой бэкап планируется восстановить, а не удалить как «наш».
    assert f"DRY: cp -a {bak} {cur}" in proc.stdout, proc.stdout
    assert "восстановить чужой drop-in" in proc.stdout
    assert f"DRY: rm -f {bak}" in proc.stdout


def test_owned_state_reads_tab_separated_marker(tmp_path):
    marker = tmp_path / "owned"
    marker.write_text(
        "# path<TAB>owner\n"
        "/opt/zapret\trouteweave\n"
        "/usr/local/bin/mihomo\tpreexisting\n",
        encoding="utf-8",
    )
    script = (
        f"OWNED_MARKER={shlex.quote(str(marker))}\n"
        + extract_function("owned_state")
        + '\nfor p in "$@"; do printf "%s=%s\\n" "$p" "$(owned_state "$p")"; done\n'
    )
    paths = [
        "/opt/zapret",
        "/usr/local/bin/mihomo",
        "/etc/systemd/system/mihomo.service",
    ]
    proc = subprocess.run(
        ["bash", "-c", script, "bash", *paths],
        check=False,
        text=True,
        capture_output=True,
        env=BASE_ENV,
    )

    assert proc.returncode == 0, proc.stderr
    assert "/opt/zapret=routeweave" in proc.stdout
    assert "/usr/local/bin/mihomo=preexisting" in proc.stdout
    assert "/etc/systemd/system/mihomo.service=unknown" in proc.stdout


def test_static_uninstall_invariants():
    text = UNINSTALL.read_text(encoding="utf-8")

    assert "ufw --force reset" not in text
    assert not re.search(r"\becho\b[^\n]*\$(PANEL_PASS|MIHOMO_SECRET|TG_SECRET)\b", text)
    assert not re.search(r"\bprintf\b[^\n]*\$(PANEL_PASS|MIHOMO_SECRET|TG_SECRET)\b", text)

    assert "--purge" in text
    assert "--dry-run" in text
    assert "ROUTEWEAVE_ETC" in text
    assert "ROUTEWEAVE_BACKUP_DIR" in text
    assert "ip_forward.orig" in text
    assert "owned_state()" in text
    assert "restore_dropin()" in text
    assert "is_routeweave_dropin()" in text

    # Ошибки не прерывают удаление, но дают код возврата 1.
    assert "ERRORS=$((ERRORS + 1))" in text
    assert 'if [ "$ERRORS" -gt 0 ]' in text
    assert "exit 1" in text


MESSAGE_PREFIXES = ("printf", "echo", "err", "warn", "info", "ok")


def compose_invocations(text: str) -> list[str]:
    """Строки, где compose реально вызывается (сообщения и комментарии — нет)."""
    calls = []
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        if stripped.startswith(MESSAGE_PREFIXES):
            continue
        if "docker compose" in stripped:
            calls.append(stripped)
    return calls


def test_static_compose_down_supplies_server_ip():
    """Без SERVER_IP compose падает на `${SERVER_IP:?}` даже при down."""
    text = UNINSTALL.read_text(encoding="utf-8")
    calls = compose_invocations(text)

    assert calls, calls
    for call in calls:
        assert "down" in call, call
        # Ровно одна переменная подстановки — SERVER_IP, инлайном.
        assert "SERVER_IP=" in call, call
        # --env-file не годится: godotenv не обязан понимать '\'' из .env.
        assert "--env-file" not in call, call


