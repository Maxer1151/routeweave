"""WDTT в установщике: override compose, drop-in docker и сохранение .env.tgws.

Проверяется:
- base docker-compose.yml не публикует порт на WDTT (иначе установка без
  WDTT падает на bind несуществующего адреса), а docker-compose.wdtt.yml
  публикует ровно один порт на ${WDTT_SERVER_IP};
- install.sh подключает override только при существующем wdtt0 и пишет
  drop-in docker.service.d с маркером владельца;
- env_set_line/env_del_line меняют только управляемые ключи .env.tgws,
  сохраняя комментарии и ручной тюнинг.
"""

import re
import shlex
import stat
import subprocess
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
INSTALL = REPO_ROOT / "install.sh"
UNINSTALL = REPO_ROOT / "uninstall.sh"
BASE_COMPOSE = REPO_ROOT / "docker-compose.yml"
WDTT_COMPOSE = REPO_ROOT / "docker-compose.wdtt.yml"
DROPIN = REPO_ROOT / "templates" / "docker-10-wdtt.conf"

MARKER = "# Generated by Routeweave installer"
BASE_ENV = {
    "PATH": "/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin",
    "LANG": "C.UTF-8",
    "LC_ALL": "C.UTF-8",
    "HOME": "/tmp",
}


def extract_function(script: Path, name: str) -> str:
    """Собрать одну функцию из скрипта по имени (как в test_install_tgws.py)."""
    text = script.read_text(encoding="utf-8")
    match = re.search(
        rf"^{re.escape(name)}\(\) \{{[^\n]*\n.*?^\}}\n",
        text,
        re.MULTILINE | re.DOTALL,
    )
    assert match, f"{script.name}: не найдена функция {name}"
    return match.group(0)


def run_snippet(script: str, args: list[str]) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["bash", "-c", script, "bash", *args],
        check=False,
        text=True,
        capture_output=True,
        env=BASE_ENV,
    )


def test_dropin_has_marker_and_orders_docker_after_wdtt():
    text = DROPIN.read_text(encoding="utf-8")
    assert text.splitlines()[0] == MARKER
    assert "After=wdtt.service" in text
    assert "[Unit]" in text


def test_base_compose_has_no_wdtt_bind_but_override_does():
    base = BASE_COMPOSE.read_text(encoding="utf-8")
    assert "WDTT_SERVER_IP" not in base
    assert base.count(":1443:1443") == 1

    override = WDTT_COMPOSE.read_text(encoding="utf-8")
    assert override.count(":1443:1443") == 1
    assert "${WDTT_SERVER_IP:-10.66.66.1}:1443:1443" in override


def test_install_wires_override_and_dropin():
    text = INSTALL.read_text(encoding="utf-8")
    assert 'COMPOSE_OVERRIDE="$APP_DIR/docker-compose.wdtt.yml"' in text
    assert 'DOCKER_DROPIN=/etc/systemd/system/docker.service.d/10-wdtt.conf' in text
    assert "templates/docker-10-wdtt.conf" in text
    # Override подключается только при известном адресе WDTT; иначе — base.
    assert 'docker compose -f docker-compose.yml -f "$COMPOSE_OVERRIDE" up -d' in text
    assert 'SERVER_IP="$SERVER_IP" WDTT_SERVER_IP="$wdtt_ip"' in text
    # Проверка фактических публикаций после старта контейнера.
    assert "PortBindings" in text
    assert "не опубликован на" in text
    # wdtt_ipv4 не должен зависеть от head/SIGPIPE.
    helper = extract_function(INSTALL, "wdtt_ipv4")
    assert "ip -4 -o addr show dev" in helper
    assert "head" not in helper


def test_uninstall_dropin_removal_requires_marker():
    text = UNINSTALL.read_text(encoding="utf-8")
    assert 'DOCKER_DROPIN=/etc/systemd/system/docker.service.d/10-wdtt.conf' in text
    assert 'DOCKER_DROPIN_MARKER=' in text
    section = text[text.index("Drop-in docker.service"):text.index("do_systemctl daemon-reload")]
    assert 'head -n1 "$DOCKER_DROPIN"' in section
    assert 'grep -qxF "$DOCKER_DROPIN_MARKER"' in section
    assert "оставлен без изменений" in section
    assert "rmdir --ignore-fail-on-non-empty" in section
    # Удаление только после проверки маркера (сначала grep, потом do_rm).
    assert section.index("grep -qxF") < section.index("do_rm \"$DOCKER_DROPIN\"")


def test_env_set_line_replaces_managed_and_keeps_manual_keys(tmp_path):
    env_file = tmp_path / ".env.tgws"
    env_file.write_text(
        "# ручной комментарий: этот ключ добавлен вручную\n"
        "TG_SECRET='old-secret'\n"
        "TG_CF_IP='1.2.3.4'\n"
        "BASE_DOMAIN='old.example'\n"
        "BASE_DOMAIN='duplicate.example'\n"
        "TG_PINNED_UPSTREAM='ws'\n"
        "TG_CF_WORKER_DOMAIN=''\n",
        encoding="utf-8",
    )
    env_file.chmod(0o640)

    script = (
        "set -Eeuo pipefail\n"
        "die() { printf 'DIE: %s\\n' \"$*\" >&2; exit 1; }\n"
        + extract_function(INSTALL, "env_line")
        + extract_function(INSTALL, "env_set_line")
        + extract_function(INSTALL, "env_del_line")
        + f"\nenv_set_line {shlex.quote(str(env_file))} TG_SECRET "
        + shlex.quote("n'ew")
        + "\n"
        + f"env_set_line {shlex.quote(str(env_file))} BASE_DOMAIN new.example\n"
        + f"env_del_line {shlex.quote(str(env_file))} TG_PINNED_UPSTREAM\n"
    )
    proc = run_snippet(script, [])
    assert proc.returncode == 0, proc.stderr

    content = env_file.read_text(encoding="utf-8")
    lines = content.splitlines()
    assert "# ручной комментарий: этот ключ добавлен вручную" in lines
    assert "TG_CF_IP='1.2.3.4'" in lines
    assert "TG_SECRET='n'\\''ew'" in lines
    assert lines.count("BASE_DOMAIN='new.example'") == 1
    assert not any(line.startswith("BASE_DOMAIN='old.example'") for line in lines)
    assert not any(line.startswith("BASE_DOMAIN='duplicate") for line in lines)
    assert not any(line.startswith("TG_PINNED_UPSTREAM=") for line in lines)
    assert "TG_CF_WORKER_DOMAIN=''" in lines
    # Права исходного файла сохраняются (fallback — 0640).
    assert stat.S_IMODE(env_file.stat().st_mode) == 0o640
    # Временные файлы не остаются рядом.
    assert not list(tmp_path.glob(".env-set.*")) and not list(tmp_path.glob(".env-del.*"))


def test_env_del_line_missing_key_is_noop(tmp_path):
    env_file = tmp_path / ".env.tgws"
    original = "# comment\nTG_SECRET='s'\nTG_CF_IP='1.2.3.4'\n"
    env_file.write_text(original, encoding="utf-8")

    script = (
        "set -Eeuo pipefail\n"
        "die() { printf 'DIE: %s\\n' \"$*\" >&2; exit 1; }\n"
        + extract_function(INSTALL, "env_line")
        + extract_function(INSTALL, "env_set_line")
        + extract_function(INSTALL, "env_del_line")
        + f"\nenv_del_line {shlex.quote(str(env_file))} TG_PINNED_UPSTREAM\n"
    )
    proc = run_snippet(script, [])
    assert proc.returncode == 0, proc.stderr
    assert env_file.read_text(encoding="utf-8") == original
    assert not list(tmp_path.glob(".env-del.*"))


def test_env_set_line_creates_missing_file_0640(tmp_path):
    env_file = tmp_path / ".env.tgws"
    script = (
        "set -Eeuo pipefail\n"
        "die() { printf 'DIE: %s\\n' \"$*\" >&2; exit 1; }\n"
        + extract_function(INSTALL, "env_line")
        + extract_function(INSTALL, "env_set_line")
        + extract_function(INSTALL, "env_del_line")
        + f"\nenv_set_line {shlex.quote(str(env_file))} TG_SECRET secret\n"
    )
    proc = run_snippet(script, [])
    assert proc.returncode == 0, proc.stderr
    assert env_file.read_text(encoding="utf-8") == "TG_SECRET='secret'\n"
    assert stat.S_IMODE(env_file.stat().st_mode) == 0o640


def test_install_preserves_tgws_env_and_has_no_cf_ip_literal():
    text = INSTALL.read_text(encoding="utf-8")
    # Управляемые ключи обновляются построчно, без перезаписи файла целиком.
    assert 'env_set_line "$ETC/.env.tgws" TG_SECRET' in text
    assert 'env_set_line "$ETC/.env.tgws" BASE_DOMAIN' in text
    assert 'env_set_line "$ETC/.env.tgws" TG_CF_WORKER_DOMAIN' in text
    assert 'env_del_line "$ETC/.env.tgws" TG_PINNED_UPSTREAM' in text
    assert 'if [ -f "$ETC/.env.tgws" ]; then' in text
    # Литерала TG_CF_IP в установщике быть не должно: сохранение универсальное.
    assert "TG_CF_IP" not in text
