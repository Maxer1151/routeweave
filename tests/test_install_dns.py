"""Тесты логики DNS в install.sh/uninstall.sh без root.

Проверяются два инварианта:
- хелпер is_routeweave_dropin в обоих скриптах одинаково отличает свой
  drop-in systemd-resolved от чужого (маркер и совместимость со старым
  содержимым);
- апдейтер списков берёт Bearer-секрет из уже прочитанного .env, а не
  разбирает файл через sed (тот оставлял кавычки и ломал авторизацию).
"""

import re
import subprocess
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[1]
SCRIPTS = ("install.sh", "uninstall.sh")
UPDATE_LISTS = REPO_ROOT / "templates" / "routeweave-update-lists.sh"

MARKER = "# Generated by Routeweave installer"
OWN_CONTENT = "[Resolve]\nDNSStubListener=no\n"


def extract_helper(script_name):
    """Собрать маркер и функцию is_routeweave_dropin из скрипта."""
    text = (REPO_ROOT / script_name).read_text(encoding="utf-8")
    marker = re.search(r"^RESOLVED_MARKER=.*$", text, re.MULTILINE)
    assert marker, f"{script_name}: не найдена константа RESOLVED_MARKER"
    func = re.search(
        r"^is_routeweave_dropin\(\) \{\n.*?^\}\n", text, re.MULTILINE | re.DOTALL
    )
    assert func, f"{script_name}: не найдена функция is_routeweave_dropin"
    return marker.group(0) + "\n" + func.group(0)


def run_helper(script_name, target, tmp_path):
    """Выполнить извлечённый хелпер в bash и вернуть его код возврата."""
    target_path = tmp_path / target
    if target == "marker.conf":
        target_path.write_text(MARKER + "\n" + OWN_CONTENT, encoding="utf-8")
    elif target == "own.conf":
        # Совместимость: файл старой установки без маркера, но с нашим
        # содержимым, тоже считается своим.
        target_path.write_text(OWN_CONTENT, encoding="utf-8")
    elif target == "foreign.conf":
        target_path.write_text("[Resolve]\nDNSStubListener=yes\n", encoding="utf-8")

    script = (
        "RESOLVED_DROPIN=/nonexistent\n"
        + extract_helper(script_name)
        + 'if is_routeweave_dropin "$1"; then exit 0; fi\nexit 1\n'
    )
    proc = subprocess.run(
        ["bash", "-c", script, "bash", str(target_path)],
        check=False,
        text=True,
        capture_output=True,
    )
    return proc


@pytest.mark.parametrize("script_name", SCRIPTS)
@pytest.mark.parametrize(
    ("target", "expected"),
    [
        ("marker.conf", 0),
        ("own.conf", 0),
        ("foreign.conf", 1),
        ("absent.conf", 1),
    ],
)
def test_is_routeweave_dropin(script_name, target, expected, tmp_path):
    proc = run_helper(script_name, target, tmp_path)
    assert proc.returncode == expected, (
        f"{script_name}, {target}: rc={proc.returncode}, "
        f"stderr={proc.stderr.strip()}"
    )


def test_update_lists_uses_env_secret():
    """Страховка от возврата дефекта: sed оставлял кавычки в секрете."""
    text = UPDATE_LISTS.read_text(encoding="utf-8")
    assert "sed -n 's/^MIHOMO_SECRET=//p'" not in text
    assert "${MIHOMO_SECRET:-}" in text
